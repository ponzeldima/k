TOKEN = re.compile(r"(\*\*.+?\*\*|_\{.+?\}|\^\{.+?\}|`.+?`)")
NBSP = " "


def nobreak(text):
    """Нерозривні пробіли: число не відривається від одиниці і від знака «=»."""
    text = re.sub(r"(\d) (с|дет\./год|шт\.|місц)", rf"\1{NBSP}\2", text)
    return re.sub(r" ([=≈<>]) (?=\d)", rf"{NBSP}\1{NBSP}", text)


def add_runs(par, text, size, color=TEXT, bold=False, font=FONT):
    """Розмітка: **жирний**, _{нижній індекс}, ^{верхній індекс}, `моноширинний`."""
    for part in TOKEN.split(nobreak(text)):
        if not part:
            continue
        b, base, f, t = bold, 0, font, part
        if part.startswith("**"):
            b, t = True, part[2:-2]
        elif part.startswith("_{"):
            base, t = -25000, part[2:-1]
        elif part.startswith("^{"):
            base, t = 30000, part[2:-1]
        elif part.startswith("`"):
            f, t = MONO, part[1:-1]
        r = par.add_run()
        r.text = t
        r.font.size = Pt(size)
        r.font.bold = b
        r.font.name = f
        r.font.color.rgb = color
        if base:
            r.font._element.set("baseline", str(base))


def set_bullet(par, level=0, char="•"):
    pPr = par._p.get_or_add_pPr()
    indent = Inches(0.28)
    pPr.set("marL", str(int(indent * (level + 1))))
    pPr.set("indent", str(-int(indent)))
    bf = pPr.makeelement(qn("a:buFont"), {"typeface": "Arial"})
    bc = pPr.makeelement(qn("a:buChar"), {"char": char})
    pPr.append(bf)
    pPr.append(bc)


def textbox(slide, x, y, w, h, paras, size=18, color=TEXT, anchor=MSO_ANCHOR.TOP,
            align=PP_ALIGN.LEFT, after=8, font=FONT, fill=None, name=None, margin=0.05):
    """paras: рядки або кортежі (текст, {bullet, level, size, color, bold, after, align})."""
    tb = slide.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h))
    if name:
        tb.name = name
    tf = tb.text_frame
    tf.word_wrap = True
    tf.vertical_anchor = anchor
    for side in ("left", "right", "top", "bottom"):
        setattr(tf, f"margin_{side}", Inches(margin))
    if fill is not None:
        tb.fill.solid()
        tb.fill.fore_color.rgb = fill
    for i, item in enumerate(paras):
        text, opt = (item, {}) if isinstance(item, str) else item
        par = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        par.alignment = opt.get("align", align)
        par.space_after = Pt(opt.get("after", after))
        add_runs(par, text, opt.get("size", size), opt.get("color", color),
                 opt.get("bold", False), opt.get("font", font))
        if opt.get("bullet"):
            set_bullet(par, opt.get("level", 0), "–" if opt.get("level", 0) else "•")
    return tb


def B(text, level=0, **kw):
    return (text, {"bullet": True, "level": level, **kw})


def title(slide, text):
    t = slide.shapes.title
