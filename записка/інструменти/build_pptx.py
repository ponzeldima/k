def crop(data, box):
    buf = io.BytesIO()
    Image.open(io.BytesIO(data)).crop(box).save(buf, "PNG")
    return buf.getvalue()


def picture(slide, src, x, y, w, h, caption=None):
    """Вписує зображення в прямокутник зі збереженням пропорцій, центрує; підпис знизу."""
    data = src if isinstance(src, bytes) else Path(src).read_bytes()
    iw, ih = Image.open(io.BytesIO(data)).size
    cap_h = 0.35 if caption else 0
    box_h = h - cap_h
    scale = min(w / iw, box_h / ih)
    pw, ph = iw * scale, ih * scale
    px, py = x + (w - pw) / 2, y + (box_h - ph) / 2
    pic = slide.shapes.add_picture(io.BytesIO(data), Inches(px), Inches(py), Inches(pw), Inches(ph))
    if caption:
        textbox(slide, x, py + ph + 0.02, w, 0.33, [caption], size=12, color=GRAY,
                align=PP_ALIGN.CENTER, after=0)
    return pic


def table(slide, x, y, widths, rows, size=15, code_cols=(), row_h=0.45, header_size=None):
    nr, nc = len(rows), len(rows[0])
    shape = slide.shapes.add_table(nr, nc, Inches(x), Inches(y), Inches(sum(widths)),
                                   Inches(row_h * nr))
    tbl = shape.table
    for j, w in enumerate(widths):
        tbl.columns[j].width = Inches(w)
    for i, row in enumerate(rows):
        tbl.rows[i].height = Inches(row_h)
        for j, val in enumerate(row):
            cell = tbl.cell(i, j)
            cell.margin_left = cell.margin_right = Inches(0.08)
            cell.margin_top = cell.margin_bottom = Inches(0.04)
            cell.vertical_anchor = MSO_ANCHOR.MIDDLE
            tf = cell.text_frame
            tf.word_wrap = True
            par = tf.paragraphs[0]
            if i == 0:
                add_runs(par, val, header_size or size, RGBColor(0xFF, 0xFF, 0xFF), bold=True)
            else:
                add_runs(par, val, size - (1 if j in code_cols else 0), TEXT,
                         font=MONO if j in code_cols else FONT)
    return shape


